/**
 * fetch-inter-fonts.js — 把 UI 字体（Inter）子集下载进仓库，实现**完全离线**渲染。
 *
 * 背景：index.css 此前 `@import` Google Fonts —— 对"买 U 盘、不装环境、随身离线"的产品
 * 是硬伤（无网/内网下要等网络超时才回落系统字体，数字先以系统字体渲染再跳变）。
 * 本脚本从 Google Fonts 取 woff2 落地到 gui/src/assets/fonts/，此后运行时零网络请求。
 *
 * 只取 latin / latin-ext：中文沿用系统字体栈（不引入 MB 级中文字库），Inter 只负责
 * 数字、英文与符号——而这正是老板最看重的部分。
 *
 * 只取**一份可变字体**（wght 400..600）：实测按固定字重分别请求 400 与 600 时，
 * Google 返回的是**同一份字节**（variable font），存两份纯属浪费，且会让产物里
 * 两条 @font-face 指向同一个文件。改用轴区间请求 + `font-weight: 400 600` 声明。
 *
 * 用法：node scripts/fetch-inter-fonts.js [--force]
 * 幂等：已存在的文件默认跳过（--force 覆盖）。失败不静默——退出码非 0。
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'gui', 'src', 'assets', 'fonts');
const WEIGHT_AXIS = '400..600';                 // 可变字体轴区间：覆盖 UI 用到的 400/600
const FILE_NAME = 'inter-latin-var.woff2';
const KEEP_LATIN = /U\+0000-00FF/i;
const KEEP_LATIN_EXT = /U\+0100-02AF/i;
const MODERN_UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

async function main() {
  const force = process.argv.includes('--force');
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const url = `https://fonts.googleapis.com/css2?family=Inter:wght@${WEIGHT_AXIS}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': MODERN_UA } });
  if (!res.ok) throw new Error(`Google Fonts CSS 请求失败: HTTP ${res.status}`);
  const css = await res.text();

  // 按 @font-face 块解析；只认 unicode-range 落在 latin / latin-ext 的块
  const blocks = css.split('@font-face').slice(1);
  const picked = [];
  for (const raw of blocks) {
    const block = raw.slice(0, raw.indexOf('}') + 1);
    const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1] || '';
    const fileUrl = (block.match(/url\((https:\/\/[^)]+\.woff2)\)/) || [])[1];
    const weight = (block.match(/font-weight:\s*([\d\s]+);/) || [])[1];
    if (!fileUrl) continue;
    const isLatin = KEEP_LATIN.test(range);
    const isLatinExt = KEEP_LATIN_EXT.test(range);
    if (!isLatin && !isLatinExt) continue;
    picked.push({ subset: isLatin ? 'latin' : 'latin-ext', range: range.trim(), fileUrl: fileUrl.trim(), weight: (weight || WEIGHT_AXIS).trim() });
  }
  if (picked.length === 0) throw new Error('未从字体 CSS 解析出任何 latin 子集——API 结构可能已变，请人工核对');

  // 只保留 latin（latin-ext 与 latin 同文件时按内容去重；不同文件则一并保留）
  const dest = path.join(OUT_DIR, FILE_NAME);
  const unique = [];
  const seenHash = new Set();
  for (const p of picked) {
    const r = await fetch(p.fileUrl, { headers: { 'User-Agent': MODERN_UA } });
    if (!r.ok) throw new Error(`字体文件下载失败 ${p.fileUrl}: HTTP ${r.status}`);
    const buf = Buffer.from(await r.arrayBuffer());
    if (buf.length < 1000) throw new Error(`字体文件异常小（${buf.length}B）: ${p.fileUrl}`);
    const hash = require('crypto').createHash('sha256').update(buf).digest('hex');
    if (seenHash.has(hash)) { console.log(`  跳过重复内容（${p.subset} 与已取文件字节相同）`); continue; }
    seenHash.add(hash);
    unique.push({ ...p, buf, hash });
  }
  // 取第一个（latin）落为唯一文件；多份不同内容的情况打印告警，提示人工确认
  const main0 = unique[0];
  if (unique.length > 1) {
    console.warn(`  ⚠ 解析到 ${unique.length} 份不同内容（${unique.map((u) => u.subset).join(', ')}）——仅落盘 ${FILE_NAME}（${main0.subset}）`);
  }
  if (fs.existsSync(dest) && !force) {
    const cur = require('crypto').createHash('sha256').update(fs.readFileSync(dest)).digest('hex');
    if (cur === main0.hash) console.log(`  跳过（内容一致）: ${FILE_NAME}`);
    else { fs.writeFileSync(dest, main0.buf); console.log(`  ↻ 更新（远端内容变化）: ${FILE_NAME}  ${(main0.buf.length / 1024).toFixed(1)}KB`); }
  } else {
    fs.writeFileSync(dest, main0.buf);
    console.log(`  ↓ ${FILE_NAME}  ${(main0.buf.length / 1024).toFixed(1)}KB`);
  }

  // 清理历史遗留的按字重静态文件（此前 400/600 各存一份，内容相同属浪费）
  for (const f of fs.readdirSync(OUT_DIR)) {
    if (/^inter-latin-\d+\.woff2$/.test(f)) { fs.rmSync(path.join(OUT_DIR, f)); console.log(`  ✗ 清理旧静态文件: ${f}`); }
  }

  const faceCss = [
    '@font-face {',
    "  font-family: 'Inter';",
    '  font-style: normal;',
    '  font-weight: 400 600;', // 可变字体轴区间：一份文件覆盖 UI 全部字重
    '  font-display: swap;',   // 本地文件：配合 index.html 的 rel=preload，无网络不确定性，也不会 FOIT
    `  src: url('./fonts/${FILE_NAME}') format('woff2');`,
    `  unicode-range: ${main0.range};`,
    '}',
  ].join('\n');

  const cssPath = path.join(ROOT, 'gui', 'src', 'assets', 'fonts.css');
  fs.writeFileSync(cssPath, `/* GENERATED by scripts/fetch-inter-fonts.js -- do not edit; regenerate: node scripts/fetch-inter-fonts.js --force */\n${faceCss}\n`, 'utf8');

  const all = fs.readdirSync(OUT_DIR).filter((f) => f.endsWith('.woff2'));
  const totalKb = all.reduce((s, f) => s + fs.statSync(path.join(OUT_DIR, f)).size, 0) / 1024;
  console.log(`\n完成: 目录内 ${all.length} 个 woff2, 合计 ${totalKb.toFixed(1)}KB（单文件可变字体，覆盖 400/600）`);
  console.log(`CSS 片段: ${path.relative(ROOT, cssPath)}`);
}

main().catch((e) => { console.error('[fetch-inter-fonts] 失败:', e.message); process.exit(1); });
