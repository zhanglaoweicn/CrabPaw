const fs = require('fs');
const path = require('path');
const BackgroundReviewer = require('./skill/background-reviewer');
const { GLOBAL_SKILLS_DIR, DATA_DIR } = require('./config');
const { usageTracker, provenanceTracker } = require('./skill-usage-tracker');

const MAX_AUTO_GENERATED_SKILLS = 100;
const SIMILARITY_THRESHOLD = 0.8;
const ARCHIVE_AFTER_DAYS = 30;
const MIN_SUCCESS_RATE_TO_KEEP = 0.3;

// 2026-08-18 残留修复: DATA_DIR 已是 data/.crabpaw, 原多拼 '.crabpaw' 段 → 落
// data/.crabpaw/.crabpaw/ 双嵌套。去重后与其他模块(disabled-skills.json 等)同层。
const SKILL_LIFECYCLE_FILE = path.join(DATA_DIR, 'skill-lifecycle.json');
const LIFECYCLE_CONFIG_FILE = path.join(DATA_DIR, 'lifecycle-config.json');

const DEFAULT_LIFECYCLE_CONFIG = {
  maxAutoGenerated: MAX_AUTO_GENERATED_SKILLS,
  similarityThreshold: SIMILARITY_THRESHOLD,
  archiveAfterDays: ARCHIVE_AFTER_DAYS,
  minSuccessRate: MIN_SUCCESS_RATE_TO_KEEP,
  autoReview: true,
  autoArchive: true,
};

function _loadUserConfig() {
  try {
    if (fs.existsSync(LIFECYCLE_CONFIG_FILE)) {
      const userConfig = JSON.parse(fs.readFileSync(LIFECYCLE_CONFIG_FILE, 'utf-8'));
      return { ...DEFAULT_LIFECYCLE_CONFIG, ...userConfig };
    }
  } catch (e) {
    console.warn('加载生命周期用户配置失败:', e.message);
  }
  return { ...DEFAULT_LIFECYCLE_CONFIG };
}

class SkillLifecycleManager {
  constructor(config = {}) {
    const userConfig = _loadUserConfig();
    this.config = {
      ...userConfig,
      ...config,
    };

    this.reviewer = new BackgroundReviewer({
      dataDir: DATA_DIR,
      autoCreateSkills: this.config.autoCreateSkills !== false,
    });

    this.lifecycle = this._loadLifecycle();
    this._reviewTimer = null;
    this._startPeriodicReview();
  }

  /**
   * 启动定期审查循环，每小时检查一次是否有待审查的对话
   */
  _startPeriodicReview() {
    if (!this.config.autoReview) return;
    const REVIEW_INTERVAL_MS = 60 * 60 * 1000; // 1小时
    this._reviewTimer = setInterval(() => {
      this._periodicReview().catch(err => {
        console.warn('[SkillLifecycle] 定期审查失败:', err.message);
      });
    }, REVIEW_INTERVAL_MS);
    // 不阻止进程退出
    if (this._reviewTimer.unref) this._reviewTimer.unref();
  }

  async _periodicReview() {
    // 从最近的对话历史中提取工具调用模式进行审查
    try {
      const { memoryManager } = require('./memory-system');
      if (!memoryManager) return;
      const recentMessages = memoryManager.getRecentMessages?.(20);
      if (!recentMessages || recentMessages.length < 5) return;
      await this.reviewConversation(recentMessages, `periodic_${Date.now()}`);
    } catch (_) {
      /* memoryManager 不可用时静默跳过 */
      console.warn('[skill-lifecycle.js] 空 catch 补日志:', _ && _.message);
    }

  }

  stopPeriodicReview() {
    if (this._reviewTimer) {
      clearInterval(this._reviewTimer);
      this._reviewTimer = null;
    }
  }

  _loadLifecycle() {
    try {
      if (fs.existsSync(SKILL_LIFECYCLE_FILE)) {
        return JSON.parse(fs.readFileSync(SKILL_LIFECYCLE_FILE, 'utf-8'));
      }
    } catch (e) {
      console.warn('加载技能生命周期数据失败', e.message);
    }
    return {
      skills: {},
      reviews: [],
      archives: [],
      stats: {
        totalGenerated: 0,
        totalArchived: 0,
        totalMerged: 0,
      }
    };
  }

  _saveLifecycle() {
    try {
      const dir = path.dirname(SKILL_LIFECYCLE_FILE);
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }
      fs.writeFileSync(SKILL_LIFECYCLE_FILE, JSON.stringify(this.lifecycle, null, 2), 'utf-8');
    } catch (e) {
      console.error('保存技能生命周期数据失败', e.message);
    }
  }

  async checkBeforeGenerate(skillName, description, existingSkills) {
    const autoGeneratedCount = Object.values(this.lifecycle.skills)
      .filter(s => s.source === 'auto_generated' && s.status === 'active').length;

    if (autoGeneratedCount >= this.config.maxAutoGenerated) {
      return {
        canGenerate: false,
        reason: `自生成技能数量已达上限(${this.config.maxAutoGenerated})，请先清理不常用的技能`,
        autoGeneratedCount,
      };
    }

    const similarSkill = this._findSimilarSkill(skillName, description, existingSkills);
    if (similarSkill) {
      return {
        canGenerate: false,
        reason: `已存在相似技能《${similarSkill.name}》(相似度: ${(similarSkill.similarity * 100).toFixed(0)}%)，建议使用或优化该技能`,
        similarSkill,
      };
    }

    return { canGenerate: true, autoGeneratedCount };
  }

  _findSimilarSkill(skillName, description, existingSkills) {
    if (!existingSkills || existingSkills.length === 0) return null;

    const nameLower = skillName.toLowerCase();
    const descLower = (description || '').toLowerCase();
    const nameWords = nameLower.split(/[-_\s]+/).filter(w => w.length > 2);
    const descWords = descLower.split(/\s+/).filter(w => w.length > 2);

    let bestMatch = null;
    let bestScore = 0;

    for (const skill of existingSkills) {
      const sNameLower = (skill.name || '').toLowerCase();
      const sDescLower = (skill.description || '').toLowerCase();

      let score = 0;
      let totalChecks = 0;

      if (nameWords.length > 0) {
        for (const word of nameWords) {
          totalChecks++;
          if (sNameLower.includes(word)) score++;
          if (sDescLower.includes(word)) score += 0.5;
        }
      }

      if (descWords.length > 0) {
        for (const word of descWords) {
          totalChecks++;
          if (sDescLower.includes(word)) score++;
          if (sNameLower.includes(word)) score += 0.5;
        }
      }

      if (sNameLower === nameLower) {
        score = totalChecks * 2;
      }

      const similarity = totalChecks > 0 ? score / totalChecks : 0;

      if (similarity > bestScore) {
        bestScore = similarity;
        bestMatch = { ...skill, similarity };
      }
    }

    if (bestScore >= this.config.similarityThreshold) {
      return bestMatch;
    }

    return null;
  }

  recordSkillGenerated(skillId, skillInfo) {
    this.lifecycle.skills[skillId] = {
      id: skillId,
      name: skillInfo.name || skillId,
      description: skillInfo.description || '',
      source: 'auto_generated',
      status: 'active',
      createdAt: Date.now(),
      lastUsedAt: Date.now(),
      usageCount: 0,
      successCount: 0,
      failureCount: 0,
      qualityScore: 0.5,
      dependencies: skillInfo.dependencies || {},
      generatedFrom: skillInfo.generatedFrom || '',
    };

    this.lifecycle.stats.totalGenerated++;
    this._saveLifecycle();

    try {
      provenanceTracker.recordCreation(skillId, skillInfo.provenance || 'background_review');
      usageTracker.recordCall(skillId, true);
    } catch { console.warn('[skill-lifecycle] silent catch, error swallowed'); }
  }

  recordSkillImported(skillId, skillInfo) {
    this.lifecycle.skills[skillId] = {
      id: skillId,
      name: skillInfo.name || skillId,
      description: skillInfo.description || '',
      source: 'imported',
      status: 'active',
      createdAt: Date.now(),
      lastUsedAt: Date.now(),
      usageCount: 0,
      successCount: 0,
      failureCount: 0,
      qualityScore: 0.5,
    };

    this._saveLifecycle();

    try {
      provenanceTracker.recordCreation(skillId, 'foreground');
    } catch { console.warn('[skill-lifecycle] silent catch, error swallowed'); }
  }

  recordSkillUsage(skillId, success) {
    if (!this.lifecycle.skills[skillId]) {
      this.lifecycle.skills[skillId] = {
        id: skillId,
        source: 'builtin',
        status: 'active',
        createdAt: Date.now(),
      };
    }

    const skill = this.lifecycle.skills[skillId];
    skill.lastUsedAt = Date.now();
    skill.usageCount = (skill.usageCount || 0) + 1;

    if (success) {
      skill.successCount = (skill.successCount || 0) + 1;
    } else {
      skill.failureCount = (skill.failureCount || 0) + 1;
    }

    const total = skill.successCount + skill.failureCount;
    if (total > 0) {
      skill.qualityScore = skill.successCount / total;
    }

    this._saveLifecycle();
  }

  async reviewConversation(conversationHistory, sessionId) {
    if (!this.config.autoReview) return null;
    if (!conversationHistory || conversationHistory.length < 5) return null;

    try {
      const review = await this.reviewer.reviewSession(
        sessionId || `session_${Date.now()}`,
        conversationHistory,
        { source: 'auto-review' }
      );

      if (review) {
        this.lifecycle.reviews.push({
          sessionId: review.sessionId,
          timestamp: review.timestamp,
          skillCandidates: review.skillCandidates?.length || 0,
          recommendations: review.recommendations?.length || 0,
        });

        if (this.lifecycle.reviews.length > 100) {
          this.lifecycle.reviews = this.lifecycle.reviews.slice(-50);
        }

        this._saveLifecycle();
      }

      return review;
    } catch (e) {
      console.error('后台审查失败:', e.message);
      return null;
    }
  }

  async archiveUnusedSkills() {
    if (!this.config.autoArchive) return [];

    const now = Date.now();
    const archived = [];

    for (const [skillId, skill] of Object.entries(this.lifecycle.skills)) {
      if (skill.source === 'builtin') continue;
      if (skill.status !== 'active') continue;

      try {
        if (!provenanceTracker.canAutoCurate(skillId)) {
          continue;
        }
      } catch { console.warn('[skill-lifecycle] silent catch, error swallowed'); }

      const daysSinceLastUse = (now - (skill.lastUsedAt || skill.createdAt)) / (24 * 60 * 60 * 1000);
      const successRate = skill.usageCount > 0
        ? (skill.successCount || 0) / skill.usageCount
        : 0.5;

      const shouldArchive = (
        daysSinceLastUse > this.config.archiveAfterDays &&
        successRate < this.config.minSuccessRate
      ) || (
        skill.usageCount === 0 &&
        daysSinceLastUse > this.config.archiveAfterDays * 2
      );

      if (shouldArchive) {
        skill.status = 'archived';
        skill.archivedAt = now;
        skill.archiveReason = daysSinceLastUse > this.config.archiveAfterDays * 2
          ? '从未使用'
          : `低成功率 (${(successRate * 100).toFixed(0)}%)`;

        this.lifecycle.archives.push({
          skillId,
          name: skill.name,
          archivedAt: now,
          reason: skill.archiveReason,
          usageCount: skill.usageCount || 0,
          successRate,
        });

        this.lifecycle.stats.totalArchived++;
        archived.push({
          skillId,
          name: skill.name,
          reason: skill.archiveReason,
        });
      }
    }

    if (archived.length > 0) {
      this._saveLifecycle();
      console.log(`📦 已归档${archived.length} 个不常用技能`);
    }

    return archived;
  }

  findMergeCandidates() {
    const activeSkills = Object.values(this.lifecycle.skills)
      .filter(s => s.source === 'auto_generated' && s.status === 'active');

    const candidates = [];

    for (let i = 0; i < activeSkills.length; i++) {
      for (let j = i + 1; j < activeSkills.length; j++) {
        const skillA = activeSkills[i];
        const skillB = activeSkills[j];

        const similarity = this._calculateSimilarity(
          skillA.name + ' ' + skillA.description,
          skillB.name + ' ' + skillB.description
        );

        if (similarity > 0.6) {
          candidates.push({
            skillA: { id: skillA.id, name: skillA.name },
            skillB: { id: skillB.id, name: skillB.name },
            similarity,
            suggestion: `技能「${skillA.name}」和「${skillB.name}」功能相似，建议合并`,
          });
        }
      }
    }

    return candidates.sort((a, b) => b.similarity - a.similarity);
  }

  _calculateSimilarity(textA, textB) {
    const wordsA = new Set(textA.toLowerCase().split(/\s+/).filter(w => w.length > 2));
    const wordsB = new Set(textB.toLowerCase().split(/\s+/).filter(w => w.length > 2));

    if (wordsA.size === 0 || wordsB.size === 0) return 0;

    let intersection = 0;
    for (const word of wordsA) {
      if (wordsB.has(word)) intersection++;
    }

    const union = wordsA.size + wordsB.size - intersection;
    return union > 0 ? intersection / union : 0;
  }

  getSkillSource(skillId) {
    const skill = this.lifecycle.skills[skillId];
    if (skill) return skill.source;

    const builtinPath = path.join(GLOBAL_SKILLS_DIR, '..', '..', 'skills', skillId);
    if (fs.existsSync(builtinPath)) return 'builtin';

    const globalPath = path.join(GLOBAL_SKILLS_DIR, skillId);
    if (fs.existsSync(globalPath)) {
      try {
        const skillMd = path.join(globalPath, 'SKILL.md');
        if (fs.existsSync(skillMd)) {
          const content = fs.readFileSync(skillMd, 'utf-8');
          if (content.includes('auto_generated: true')) return 'auto_generated';
        }
      } catch (e) {
        console.debug('[skill-lifecycle] 检测技能来源失败', e.message);
      }
      return 'imported';
    }

    return 'unknown';
  }

  getStats() {
    const skills = Object.values(this.lifecycle.skills);
    const active = skills.filter(s => s.status === 'active');
    const archived = skills.filter(s => s.status === 'archived');

    return {
      total: skills.length,
      active: active.length,
      archived: archived.length,
      bySource: {
        builtin: skills.filter(s => s.source === 'builtin').length,
        auto_generated: skills.filter(s => s.source === 'auto_generated').length,
        imported: skills.filter(s => s.source === 'imported').length,
      },
      autoGeneratedActive: active.filter(s => s.source === 'auto_generated').length,
      maxAutoGenerated: this.config.maxAutoGenerated,
      totalGenerated: this.lifecycle.stats.totalGenerated,
      totalArchived: this.lifecycle.stats.totalArchived,
      totalMerged: this.lifecycle.stats.totalMerged,
      recentReviews: this.lifecycle.reviews.slice(-5),
      mergeCandidates: this.findMergeCandidates().length,
    };
  }

  getSkillDetail(skillId) {
    return this.lifecycle.skills[skillId] || null;
  }

  restoreArchivedSkill(skillId) {
    const skill = this.lifecycle.skills[skillId];
    if (skill && skill.status === 'archived') {
      skill.status = 'active';
      skill.lastUsedAt = Date.now();
      delete skill.archivedAt;
      delete skill.archiveReason;
      this._saveLifecycle();
      return true;
    }
    return false;
  }
}

let instance = null;

function getSkillLifecycleManager(config) {
  if (!instance) {
    instance = new SkillLifecycleManager(config);
  }
  return instance;
}

module.exports = {
  SkillLifecycleManager,
  getSkillLifecycleManager,
  MAX_AUTO_GENERATED_SKILLS,
};
