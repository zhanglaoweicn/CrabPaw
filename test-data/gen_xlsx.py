def build(fname, title, headers, rows, num_cols=(), date_cols=(), total_col=None):
    wb = Workbook()
    ws = wb.active
    ws.title = "数据"
    last_col = len(headers) + 1
    setup_sheet(ws, title=title, last_col=last_col)
    for ci, h in enumerate(headers, start=2):
        ws.cell(row=4, column=ci, value=h)
    style_header_row(ws, row_num=4, col_start=2, col_end=last_col)
    for i, row in enumerate(rows):
        rn = 5 + i
        for ci, v in enumerate(row, start=2):
            c = ws.cell(row=rn, column=ci, value=v)
        style_data_row(ws, row_num=rn, col_start=2, col_end=last_col, row_index=i)
        for ci in num_cols:
            c = ws.cell(row=rn, column=ci)
            c.number_format = FORMATS['decimal_2']
            c.alignment = align_number()
        for ci in date_cols:
            c = ws.cell(row=rn, column=ci)
            if isinstance(c.value, (dt.date, dt.datetime)):
                c.number_format = FORMATS['date']
            c.alignment = align_date()
    if total_col:
        tr = 5 + len(rows)
        ws.cell(row=tr, column=2, value="合计")
        letter = get_column_letter(total_col)
        ws.cell(row=tr, column=total_col, value=f"=SUM({letter}5:{letter}{tr-1})")
        ws.cell(row=tr, column=total_col).number_format = FORMATS['decimal_2']
        style_total_row(ws, row_num=tr, col_start=2, col_end=last_col)
    auto_fit_columns(ws, min_width=8, max_width=28, header_row=4, data_start_row=5)
    auto_fit_row_heights(ws, header_row=4, data_start_row=5)
    wb.properties.creator = "Z.ai"
    wb.save(os.path.join(OUT, fname))
    print("saved", fname)

